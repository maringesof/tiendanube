-- Tabla propia del microservicio de pedidos (Oracle Autonomous Database).
CREATE TABLE orders (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Referencia lógica al _id de MongoDB (no es llave foránea entre bases).
  product_id    VARCHAR2(64)  NOT NULL,
  product_name  VARCHAR2(120) NOT NULL,
  unit_price    NUMBER(12, 2) NOT NULL,
  quantity      NUMBER(10)    NOT NULL CHECK (quantity > 0),
  total         NUMBER(14, 2) NOT NULL,
  customer_name VARCHAR2(120) NOT NULL,
  status        VARCHAR2(20)  DEFAULT 'pendiente' NOT NULL
                CHECK (status IN ('pendiente', 'enviado', 'entregado', 'cancelado')),
  created_by    VARCHAR2(128) NOT NULL,
  created_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
)
